// id 패턴 -> 모양
const SHAPE_RULES: [RegExp, string][] = [
  [/_sword$/, 'sword'],
  [/_pickaxe$/, 'pickaxe'],
  [/_axe$/, 'axe'],
  [/_shovel$/, 'shovel'],
  [/_hoe$/, 'hoe'],
  [/_helmet$/, 'helmet'],
  [/_chestplate$/, 'chestplate'],
  [/_leggings$/, 'leggings'],
  [/_boots$/, 'boots'],
  [/_ingot$/, 'ingot'],
  [/^(diamond|emerald|lapis_lazuli|amethyst)$/, 'gem'],
  [/_ore$/, 'ore_block'],
  [/_log$/, 'log'],
  [/_planks?$/, 'plank'],
  [/^(wheat|carrot|potato|beetroot|sugar_cane|nether_wart|bamboo|kelp|torchflower)$/, 'plant'],
  [/^(melon_block|pumpkin|cocoa_beans|sweet_berries|glow_berries)$/, 'crop_top'],
  [/^(potion_|potion$)/, 'potion'],
  [/^(bow|crossbow)$/, 'bow'],
  [/^shield$/, 'shield'],
  [/^book|enchanted_book$/, 'book'],
  [/^(redstone|redstone_torch|repeater|comparator|observer|dispenser|dropper|note_block|target_block|daylight_detector|detector_rail|redstone_lamp)$/, 'redstone'],
  [/^(wool|carpet|dye|banner|bed)$/, 'wool_ball'],
  [/^(minecart|boat|rail|powered_rail)$/, 'cart'],
  [/^(ench_)/, 'spark'],
  [/^(apple|golden_apple|bread|cooked_beef|cooked_porkchop|cooked_chicken|golden_carrot|cake|cookie|pumpkin_pie|honey_bottle|melon|cod|salmon)$/, 'food'],
];

function pickShape(item: { id: string; category: string; subcategory: string }): Shape {
  for (const [re, shape] of SHAPE_RULES) {
    if (re.test(item.id)) return SHAPES[shape];
  }
  if (item.category === '몹') {
    if (item.subcategory === '보스') return SHAPES.boss;
    if (item.subcategory === '적대적') return SHAPES.hostile;
    return SHAPES.creature;
  }
  if (item.category === '작물') return SHAPES.plant;
  if (item.category === '블록') return SHAPES.block;
  if (item.category === '기타') return SHAPES.spark;
  return SHAPES.generic;
}

