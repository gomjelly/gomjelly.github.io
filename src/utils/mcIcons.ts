function pickColor(item: { id: string; category: string }) {
  for (const [re, color] of COLOR_RULES) {
    if (re.test(item.id)) return color;
  }
  return CATEGORY_COLOR[item.category] ?? CATEGORY_COLOR['아이템'];
}

export function getIcon(item: { id: string; category: string; subcategory: string }) {
  return { shape: pickShape(item), color: pickColor(item) };
}
